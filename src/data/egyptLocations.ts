export const ALL_GOVERNORATE_NAMES: string[] = EGYPT_GOVERNORATES.map((g) => g.name);

export function getCitiesForGovernorate(governorateName: string): CityLocation[] {
  if (!governorateName || governorateName === 'الكل') return [];
  return EGYPT_GOVERNORATES.find((g) => g.name === governorateName)?.cities ?? [];
}

export function getAreasForCity(governorateName: string, cityName: string): string[] {
  if (!governorateName || governorateName === 'الكل' || !cityName || cityName === 'الكل') {
    return [];
  }
  const cities = getCitiesForGovernorate(governorateName);
  return cities.find((c) => c.name === cityName)?.areas ?? [];
}

export function resolveCoordinatesForLocation(
  governorateName?: string,
  cityName?: string
): Coordinates {
  const gov = EGYPT_GOVERNORATES.find((g) => g.name === governorateName);
  if (!gov) return { lat: 30.0444, lng: 31.2357 };
  const city = gov.cities.find((c) => c.name === cityName);
  return city?.coordinates ?? gov.coordinates;
}
